function metadata(e) {
  let l = lf[e],
    a = directions.find((t) => e === "/training/" + t.id);
  a && (l = [a.name, a.subtitle + " " + a.text]);
  let d = trainers.find((t) => e === "/trainers/" + t.id);
  return (
    d && (l = [d.name + " — демо-профиль", d.role + ". " + d.bio]),
    {
      title: (l?.[0] ?? "Страница не найдена") + " — LegacyLab Fitness",
      description:
        l?.[1] ?? "Эта страница не найдена. Выберите другой раздел сайта.",
      exists: !!l,
      noindex: ["/account", "/booking"].includes(e),
      canonical: config.url + e,
    }
  );
}
