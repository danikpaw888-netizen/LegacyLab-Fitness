function todayISO(e = new Date()) {
  return new Intl.DateTimeFormat("en-CA", {
    timeZone: config.timeZone,
    year: "numeric",
    month: "2-digit",
    day: "2-digit",
  }).format(e);
}
function addDays(e, l) {
  let a = new Date(e + "T12:00:00Z");
  return (a.setUTCDate(a.getUTCDate() + l), a.toISOString().slice(0, 10));
}
function dateLabel(e, l = { day: "numeric", month: "long" }) {
  return new Intl.DateTimeFormat("ru-RU", { ...l, timeZone: "UTC" }).format(
    new Date(e + "T12:00:00Z"),
  );
}
